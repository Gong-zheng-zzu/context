// Command generate_test_data builds the layered-detection evaluation corpus used by
// experiments/scripts/ablation_adversarial_eval.py.
//
// The corpus answers a specific question: can obfuscated or context-ambiguous
// sensitive data still be recognised, without flagging lookalike non-sensitive
// values? Four categories are therefore produced, balanced by construction:
//
//	standard       sensitive values in canonical form          (expected_sensitive = true)
//	bypass_attack  sensitive values deliberately obfuscated    (expected_sensitive = true)
//	confusing      lookalikes that must NOT be flagged         (expected_sensitive = false)
//	normal         ordinary non-sensitive prose                (expected_sensitive = false)
//
// Two properties matter for the numbers to be defensible:
//
//  1. Positive samples are generated by real encoding rules, not typed by hand.
//     Identity cards carry a valid GB 11643-1999 check digit and phone numbers use
//     assigned mobile prefixes, so a detector that validates structure sees the same
//     thing it would see in production. Hand-typed literals with wrong check digits
//     would let a structural validator fail for reasons that have nothing to do with
//     obfuscation.
//  2. Generation is deterministic: the same -seed and -per-category always produce
//     the same bytes, so a dataset digest can be re-derived later.
//
// The output is deliberately separate from test_data_100.json, which historical
// results reference by digest and which this command must not touch.
package main

