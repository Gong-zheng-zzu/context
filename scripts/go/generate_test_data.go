// TestCase is the record shape consumed by ablation_adversarial_eval.py.
type TestCase struct {
	ID                int      `json:"id"`
	Content           string   `json:"content"`
	ExpectedSensitive bool     `json:"expected_sensitive"`
	SensitiveTypes    []string `json:"sensitive_types"`
	AttackType        string   `json:"attack_type"`
	Category          string   `json:"category"`
	Description       string   `json:"description"`
}

// categoryOrder fixes the emission order so the file is reproducible.
var categoryOrder = []string{"standard", "bypass_attack", "confusing", "normal"}

// idCardWeights and idCardCheckChars implement the GB 11643-1999 check digit:
// the first 17 digits are weighted, summed, and reduced modulo 11.
